// -- Lingua activa ----------------------------------
let _lang = 'pt';

function initI18n() {
  // 1. Preferencia guardada pelo utilizador
  const saved = localStorage.getItem('slb_lang');
  if (saved && TRANSLATIONS[saved]) { _lang = saved; return; }

  // 2. Lingua do browser
  const browserLang = (navigator.language || navigator.userLanguage || 'pt').slice(0, 2).toLowerCase();
  if (TRANSLATIONS[browserLang]) { _lang = browserLang; return; }

  // 3. Fallback: portugues
  _lang = 'pt';
}

function setLang(lang) {
  if (!TRANSLATIONS[lang]) return;
  _lang = lang;
  localStorage.setItem('slb_lang', lang);
}

function getLang() { return _lang; }

// Funcao principal de traducao
function t(key, vars) {
  const str = TRANSLATIONS[_lang]?.[key] || TRANSLATIONS['pt']?.[key] || key;
  if (!vars) return str;
  // Substituir variaveis: t('settings_leave_confirm', { name: 'Grupo X' })
  return str.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}

